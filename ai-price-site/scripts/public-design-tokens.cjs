const fs = require("node:fs");
const path = require("node:path");
const postcss = require("postcss");

const STYLE_FILES = Object.freeze([
  "public-tokens.css", "public-base.css", "public-components.css", "public-motion.css",
]);

function renderTokens(tokens, compatibility) {
const scope = ".gs-public-unified";
const semanticColors = {
  page: "page", surface: "surface", subtle: "neutralSurface", text: "ink",
  "text-secondary": "secondary", border: "border", "border-strong": "controlBorder",
  accent: "lime", "accent-soft": "limeSoft", low: "priceLow", high: "priceHigh",
  link: "link", focus: "focus", "map-baseline": "mapBaseline",
  "map-no-data": "mapNoData", "map-no-data-pattern": "mapNoDataPattern",
};
const aliases = {
  "color-bg-page": "page", "color-bg-surface": "surface", "color-bg-subtle": "subtle",
  "color-text-primary": "text", "color-text-secondary": "text-secondary",
  "color-border-default": "border", "color-border-strong": "border-strong",
  "color-accent": "accent", "color-accent-soft": "accent-soft",
  "color-price-low": "low", "color-price-high": "high", "color-link": "link", "color-focus": "focus",
  "color-map-low": "map-low", "color-map-high": "map-high", "color-map-baseline": "map-baseline",
  "radius-card": "radius-card", "radius-control": "radius-control",
  "font-public": "font-body", "font-price": "font-price",
};
const kebab = value => value.replace(/[A-Z]/g, letter => `-${letter.toLowerCase()}`);
const variables = [];
const add = (name, value) => variables.push(`  --gs-${name}: ${value};`);

for (const [name, value] of Object.entries(tokens.colors)) add(`palette-${kebab(name)}`, value);
for (const [name, key] of Object.entries(semanticColors)) add(name, `var(--gs-palette-${kebab(key)})`);
add("map-low", compatibility.mapLight.low);
add("map-high", compatibility.mapLight.high);
for (const [name, value] of Object.entries(tokens.radius)) add(`radius-${name}`, `${value}px`);
for (const [name, value] of Object.entries(tokens.motion)) add(`motion-${kebab(name)}`, value);
add("work-square-size", `${tokens.incomeBurden.squareSize}px`);
add("work-square-max", `${tokens.incomeBurden.maxSquareSize}px`);
add("work-square-gap", `${tokens.incomeBurden.squareGap}px`);
for (const value of tokens.spacing) add(`space-${value}`, `${value}px`);
add("font-body", tokens.fonts.body);
add("font-price", tokens.fonts.price);
add("font-hero", tokens.fonts.hero);
add("numeric-variant", tokens.fonts.numericVariant);
for (const [role, values] of Object.entries(tokens.typography)) {
  for (const [property, value] of Object.entries(values)) {
    add(`${kebab(role)}-${kebab(property)}`, `${value}${["size", "desktop", "mobile"].includes(property) ? "px" : ""}`);
  }
}
for (const [name, value] of Object.entries(tokens.layout)) add(kebab(name), `${value}px`);
// Shared public control geometry.
add("weight-emphasis", 500);
add("touch-target", `var(--gs-min-touch-target)`);
add("focus-width", "2px");
add("focus-offset", "2px");
add("control-height", "var(--gs-touch-target)");
add("tag-height", "24px");
add("checkbox-size", "18px");
add("border-width", "1px");
add("disabled-opacity", "0.5");
add("shadow-floating", "0 var(--gs-space-8) var(--gs-space-24) color-mix(in srgb, var(--gs-palette-ink) 14%, transparent)");
add("overlay", "color-mix(in srgb, var(--gs-palette-ink) 60%, transparent)");
for (const [name, value] of Object.entries(compatibility.effects)) add(name, value);

add("shadow-none", "none");
add("shadow-card", "0 1px 2px color-mix(in srgb, var(--gs-text) 5%, transparent)");
add("shadow-card-hover", "0 var(--gs-space-8) var(--gs-space-24) color-mix(in srgb, var(--gs-text) 12%, transparent)");
return [
  "/* Generated by scripts/public-design-tokens.cjs. Edit design JSON, then regenerate.",
  " * Palette/scale literals exist only in these scoped custom-property definitions. */",
  `${scope} {`, ...variables,
  ...Object.entries(aliases).map(([old, name]) => `  --${old}: var(--gs-${name});`),
  "}",
  "@media (prefers-color-scheme: dark) {", `  ${scope} {`,
  ...Object.entries(compatibility.dark).map(([name, value]) => `    --gs-${name}: ${value};`),
  "    --gs-map-no-data: var(--gs-page);", "    --gs-map-no-data-pattern: var(--gs-border);",
  "  }", "}", "",
].join("\n");
}

function ancestors(node) {
  const result = [];
  for (let parent = node.parent; parent && parent.type !== "root"; parent = parent.parent) {
    if (parent.type === "atrule") result.unshift(`@${parent.name} ${parent.params}`);
  }
  return result;
}

const colorNames = new Set(("aliceblue antiquewhite aqua aquamarine azure beige bisque black blanchedalmond blue blueviolet brown burlywood cadetblue chartreuse chocolate coral cornflowerblue cornsilk crimson cyan darkblue darkcyan darkgoldenrod darkgray darkgrey darkgreen darkkhaki darkmagenta darkolivegreen darkorange darkorchid darkred darksalmon darkseagreen darkslateblue darkslategray darkslategrey darkturquoise darkviolet deeppink deepskyblue dimgray dimgrey dodgerblue firebrick floralwhite forestgreen fuchsia gainsboro ghostwhite gold goldenrod gray grey green greenyellow honeydew hotpink indianred indigo ivory khaki lavender lavenderblush lawngreen lemonchiffon lightblue lightcoral lightcyan lightgoldenrodyellow lightgray lightgrey lightgreen lightpink lightsalmon lightseagreen lightskyblue lightslategray lightslategrey lightsteelblue lightyellow lime limegreen linen magenta maroon mediumaquamarine mediumblue mediumorchid mediumpurple mediumseagreen mediumslateblue mediumspringgreen mediumturquoise mediumvioletred midnightblue mintcream mistyrose moccasin navajowhite navy oldlace olive olivedrab orange orangered orchid palegoldenrod palegreen paleturquoise palevioletred papayawhip peachpuff peru pink plum powderblue purple rebeccapurple red rosybrown royalblue saddlebrown salmon sandybrown seagreen seashell sienna silver skyblue slateblue slategray slategrey snow springgreen steelblue tan teal thistle tomato turquoise violet wheat white whitesmoke yellow yellowgreen").split(" "));
const colorProperty = /^(?:color|background(?:-color|-image)?|(?:border|outline)(?:-(?:top|right|bottom|left|inline|block|inline-start|inline-end|block-start|block-end))?(?:-color)?|fill|stroke|text-decoration(?:-color)?|(?:box|text)-shadow|caret-color|accent-color|stop-color)$/;

function hasLiteralColor(value, property) {
  // Selectors, content strings and font/resource names are not declarations of color.
  const clean = value.replace(/url\([^)]*\)|"[^"]*"|'[^']*'/g, "");
  if (/#[\da-f]{3,8}\b|\b(?:rgba?|hsla?|hwb|lab|lch|oklab|oklch|color)\(/i.test(clean)) return true;
  return colorProperty.test(property) && (clean.match(/\b[a-z]+\b/gi) || []).some(word => colorNames.has(word.toLowerCase()));
}

/** Check parsed CSS supplied by the caller; tests provide CSS fixtures, not source text.
 * Literal token values are allowed only in the generated public-tokens.css file.
 * Reject every hover reset, including a later broad base rule for the same target.
 * The reduced-motion media query is the only intentional motion-reset exception.
 */
function inspectStyles(files) {
  const issues = [];
  const hoverEffects = [];
  const variables = new Map();
  const roots = files.map(file => ({ ...file, root: postcss.parse(file.css, { from: file.filename }) }));
  for (const { root } of roots) root.walkDecls(/^--/, decl => variables.set(decl.prop, decl.value.trim()));
  const resolveValue = (value, visited = new Set()) => {
    const match = value.trim().match(/^var\((--[\w-]+)(?:,\s*(.*))?\)$/);
    if (!match || visited.has(match[1])) return value.trim();
    visited.add(match[1]);
    return resolveValue(variables.get(match[1]) ?? match[2] ?? value, visited);
  };
  for (const { filename, root } of roots) {
    const issue = (decl, message) => issues.push(`${filename}:${decl.source?.start?.line || 1}: ${message}`);
    root.walkRules(rule => {
      const context = ancestors(rule);
      if (context.some(item => /^@(?:-webkit-)?keyframes\b/.test(item))) return;
      for (const selector of postcss.list.comma(rule.selector)) {
        if (!selector.trim().startsWith(".gs-public-unified")) issue(rule, `Selector escapes .gs-public-unified: ${selector}`);
      }
    });
    root.walkAtRules(rule => {
      if (/keyframes$/.test(rule.name) && filename !== "public-motion.css") issue(rule, "Keyframes belong in public-motion.css");
    });
    root.walkDecls(decl => {
      const property = decl.prop.toLowerCase();
      const value = decl.value.trim();
      const context = ancestors(decl);
      const token = property.startsWith("--");
      const generatedToken = token && filename === "public-tokens.css";
      if (!generatedToken && hasLiteralColor(value, property)) issue(decl, `Literal color in ${property}; use a token`);
      if (property === "font-size" && /(?:\d|\b(?:xx-small|x-small|small|medium|large|x-large|xx-large)\b)/.test(value.replace(/var\([^)]*\)/g, ""))) issue(decl, "Literal font-size; use a token");
      if (property === "box-shadow" && !/^var\(--gs-[\w-]+\)$/.test(value)) issue(decl, "box-shadow must use a variable");
      if (/^(?:animation|transition)(?:-|$)/.test(property) && filename !== "public-motion.css") issue(decl, "Motion belongs in public-motion.css");
      if (!["transform", "box-shadow"].includes(property) || decl.parent.type !== "rule") return;
      // A reset is safe only when ALL media alternatives explicitly require reduce.
      const reduced = context.some(item => item.startsWith("@media ") && postcss.list.comma(item.slice(7)).every(query => /\(\s*prefers-reduced-motion\s*:\s*reduce\s*\)/.test(query) && !/\bnot\b/.test(query)));
      if (reduced) return;
      const selectors = postcss.list.comma(decl.parent.selector).map(selector => selector.replace(/\s+/g, " ").trim());
      const reset = resolveValue(value) === "none";
      for (const selector of selectors) {
        if (reset) {
          const prior = hoverEffects.find(effect => effect.property === property && effect.target === selector && (effect.context === context.join("|") || !context.length));
          if (selector.includes(":hover") || prior) issue(decl, `${property} resets a hover effect to none: ${selector}`);
        } else if (selector.includes(":hover")) {
          hoverEffects.push({ property, target: selector.replace(/:hover\b/g, ""), context: context.join("|") });
        }
      }
    });
  }
  return issues;
}

function main(argv = process.argv.slice(2)) {
  const rootFlag = argv.indexOf("--root");
  const appDir = rootFlag < 0 ? path.resolve(__dirname, "..") : path.resolve(argv[rootFlag + 1]);
  const tokens = JSON.parse(fs.readFileSync(path.join(appDir, "design/design-tokens.json"), "utf8"));
  const compatibility = JSON.parse(fs.readFileSync(path.join(appDir, "design/public-theme-compatibility.json"), "utf8"));
  const output = renderTokens(tokens, compatibility);
  const destination = path.join(appDir, "app/public-tokens.css");
  if (!argv.includes("--check")) {
    fs.writeFileSync(destination, output);
    console.log("Generated app/public-tokens.css (inactive .gs-public-unified scope).");
    return;
  }
  const files = STYLE_FILES.map(filename => ({ filename, css: fs.readFileSync(path.join(appDir, "app", filename), "utf8").replace(/\r\n/g, "\n") }));
  const issues = inspectStyles(files);
  if (files[0].css !== output) issues.unshift("Token CSS differs from its JSON sources; run node scripts/public-design-tokens.cjs.");
  if (issues.length) throw new Error(issues.join("\n"));
  console.log("PASS: four U1 stylesheets; scoped tokens, font sizes, shadows and hover effects.");
}

module.exports = { STYLE_FILES, renderTokens, inspectStyles, main };
if (require.main === module) {
  try { main(); } catch (error) { console.error(error.message); process.exitCode = 1; }
}
