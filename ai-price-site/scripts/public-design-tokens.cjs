function hasLiteralColor(value, property) {
  // Selectors, content strings and font/resource names are not declarations of color.
  const clean = value.replace(/url\([^)]*\)|"[^"]*"|'[^']*'/g, "");
  if (/#[\da-f]{3,8}\b|\b(?:rgba?|hsla?|hwb|lab|lch|oklab|oklch|color)\(/i.test(clean)) return true;
  return colorProperty.test(property) && (clean.match(/\b[a-z]+\b/gi) || []).some(word => colorNames.has(word.toLowerCase()));
}

/** Check parsed CSS supplied by the caller; tests provide CSS fixtures, not source text.
 * Literal token values are allowed only in the generated public-tokens.css file.
 * Reject every hover reset, including a later broad base rule for the same target.
 * The reduced-motion media query is the only intentional motion-reset exception.
 */
function inspectStyles(files) {
  const issues = [];
  const hoverEffects = [];
  const variables = new Map();
  const roots = files.map(file => ({ ...file, root: postcss.parse(file.css, { from: file.filename }) }));
  for (const { root } of roots) root.walkDecls(/^--/, decl => variables.set(decl.prop, decl.value.trim()));
  const resolveValue = (value, visited = new Set()) => {
    const match = value.trim().match(/^var\((--[\w-]+)(?:,\s*(.*))?\)$/);
    if (!match || visited.has(match[1])) return value.trim();
    visited.add(match[1]);
    return resolveValue(variables.get(match[1]) ?? match[2] ?? value, visited);
  };
  for (const { filename, root } of roots) {
    const issue = (decl, message) => issues.push(`${filename}:${decl.source?.start?.line || 1}: ${message}`);
    root.walkRules(rule => {
      const context = ancestors(rule);
      if (context.some(item => /^@(?:-webkit-)?keyframes\b/.test(item))) return;
      for (const selector of postcss.list.comma(rule.selector)) {
        if (!selector.trim().startsWith(".gs-public-unified")) issue(rule, `Selector escapes .gs-public-unified: ${selector}`);
      }
    });
    root.walkAtRules(rule => {
      if (/keyframes$/.test(rule.name) && filename !== "public-motion.css") issue(rule, "Keyframes belong in public-motion.css");
    });
    root.walkDecls(decl => {
      const property = decl.prop.toLowerCase();
      const value = decl.value.trim();
      const context = ancestors(decl);
      const token = property.startsWith("--");
      const generatedToken = token && filename === "public-tokens.css";
      if (!generatedToken && hasLiteralColor(value, property)) issue(decl, `Literal color in ${property}; use a token`);
      if (property === "font-size" && /(?:\d|\b(?:xx-small|x-small|small|medium|large|x-large|xx-large)\b)/.test(value.replace(/var\([^)]*\)/g, ""))) issue(decl, "Literal font-size; use a token");
      if (property === "box-shadow" && !/^var\(--gs-[\w-]+\)$/.test(value)) issue(decl, "box-shadow must use a variable");
      if (/^(?:animation|transition)(?:-|$)/.test(property) && filename !== "public-motion.css") issue(decl, "Motion belongs in public-motion.css");
      if (!token && /^(?:transform|translate|rotate|scale)(?:-|$)/.test(property) && filename !== "public-motion.css") issue(decl, "Transforms belong in public-motion.css");
      if (/^background(?:-color|-image)?$/.test(property) && decl.parent.type === "rule") {
        const usesInk = /var\(--gs-text\)/.test(value) || resolveValue(value) === resolveValue("var(--gs-text)");
        const smallControl = selector => {
          const target = postcss.list.space(selector).at(-1) || "";
          const group = target.match(/^:(?:is|where)\((.*)\)(?::[\w-]+)*$/);
          if (group) return postcss.list.comma(group[1]).every(smallControl);
          const direct = target.replace(/:[\w-]+\([^)]*\)/g, "");
          return /\[data-gs-ui=["'](?:button|icon-button|tag)["']\]/.test(direct)
            || /^button(?=[.#:\[]|$)/.test(direct);
        };
        if (usesInk && !postcss.list.comma(decl.parent.selector).every(smallControl)) issue(decl, "Main text background is allowed only on buttons or tags");
      }
      if (!["transform", "box-shadow"].includes(property) || decl.parent.type !== "rule") return;
      // A reset is safe only when ALL media alternatives explicitly require reduce.
      const reduced = context.some(item => item.startsWith("@media ") && postcss.list.comma(item.slice(7)).every(query => /\(\s*prefers-reduced-motion\s*:\s*reduce\s*\)/.test(query) && !/\bnot\b/.test(query)));
      if (reduced) return;
      const selectors = postcss.list.comma(decl.parent.selector).map(selector => selector.replace(/\s+/g, " ").trim());
      const reset = resolveValue(value) === "none";
      for (const selector of selectors) {
        if (reset) {
          const prior = hoverEffects.find(effect => effect.property === property && effect.target === selector && (effect.context === context.join("|") || !context.length));
          if (selector.includes(":hover") || prior) issue(decl, `${property} resets a hover effect to none: ${selector}`);
        } else if (selector.includes(":hover")) {
          hoverEffects.push({ property, target: selector.replace(/:hover\b/g, ""), context: context.join("|") });
        }
      }
    });
  }
  return issues;
}

// Category 3 is usage-specific: neither a palette-wide exemption nor a text waiver.
const CONTRAST_ALLOWLIST = Object.freeze({
  "nav-underline": { tokens: ["graphic"], support: ["aria-current"], reason: "Current navigation item is also identified by aria-current and its label." },
  "selected-slider": { tokens: ["graphic", "accent"], support: ["aria-selected"], reason: "Selection is also exposed by aria-selected on the labelled option." },
  "numbered-bar": { tokens: ["graphic", "bar-low", "bar-high"], support: ["visible-text"], reason: "An adjacent visible number conveys the same quantity." },
  "progress-bar": { tokens: ["graphic", "bar-low"], support: ["aria-valuenow", "visible-text"], reason: "Progress is also available as a numeric value or visible text." },
  "pulse-ring": { tokens: ["graphic", "low", "bar-low"], support: ["visible-text"], reason: "The ring repeats the visible lowest-price label; it is not the map point itself." },
  "emphasis-border": { tokens: ["accent-border"], support: ["visible-text"], reason: "The border decorates a block whose information is stated in text." },
});
function contrastRatio(a, b) {
  const luminance = hex => {
    if (!/^#[0-9a-f]{6}$/i.test(hex)) throw new Error(`Unresolved contrast color: ${hex}`);
    const linear = [1, 3, 5].map(i => parseInt(hex.slice(i, i + 2), 16) / 255).map(v => v <= .04045 ? v / 12.92 : ((v + .055) / 1.055) ** 2.4);
    return linear.reduce((sum, v, i) => sum + v * [.2126, .7152, .0722][i], 0);
  };
  const values = [luminance(a), luminance(b)].sort((x, y) => x - y);
  return (values[1] + .05) / (values[0] + .05);
}
function checkContrastUse(palette, { category, foreground, background, role = "", support = "" }) {
  const ratio = contrastRatio(palette[foreground], palette[background]);
  if (category === "text") return { pass: ratio >= 4.5, ratio, reason: "All text requires 4.5:1; no exemption." };
  if (category === "graphic-only") return { pass: ["bar-low", "low", "bar-high", "baseline"].includes(foreground) && background === "surface" && ratio >= 3, ratio, reason: "Standalone points/lines use bar-low, low, bar-high or baseline on the white panel (the dark surface in dark mode), at least 3:1." };
  const exception = category === "redundant" && CONTRAST_ALLOWLIST[role];
  const pass = Boolean(exception && exception.tokens.includes(foreground) && exception.support.includes(support));
  return { pass, ratio, reason: pass ? exception.reason : "No approved, supported graphic exception." };
}
function inspectContrastPolicy(tokens, compatibility) {
  const light = Object.fromEntries(Object.entries(tokens.colors).map(([key, value]) => [key.replace(/[A-Z]/g, c => `-${c.toLowerCase()}`), value]));
  const issues = [];
  for (const [theme, palette] of [["light", light], ["dark", { ...light, ...compatibility.dark }]]) {
    const uses = ["text", "text-secondary", "text-muted", "low", "high", "baseline"].flatMap(foreground =>
      ["page", "surface", "subtle"].filter(background => foreground !== "low" || background !== "subtle")
        .map(background => ({ category: "text", foreground, background })));
    for (const [foreground, background] of [["on-accent", "accent"], ["low-on-soft", "accent-soft"], ["low-on-soft", "tag-low"], ["high-on-soft", "high-soft"]]) uses.push({ category: "text", foreground, background });
    for (const foreground of ["bar-low", "low", "bar-high", "baseline"]) uses.push({ category: "graphic-only", foreground, background: "surface" });
    for (const [role, entry] of Object.entries(CONTRAST_ALLOWLIST)) for (const foreground of entry.tokens) for (const background of ["page", "surface", "subtle"]) {
      uses.push({ category: "redundant", role, foreground, background, support: entry.support[0] });
    }
    for (const use of uses) {
      const result = checkContrastUse(palette, use);
      if (!result.pass) issues.push(`${theme} ${use.category} ${use.foreground}/${use.background}: ${result.ratio.toFixed(3)}:1; ${result.reason}`);
    }
  }
  return issues;
}

function main(argv = process.argv.slice(2)) {
  const rootFlag = argv.indexOf("--root");
  const appDir = rootFlag < 0 ? path.resolve(__dirname, "..") : path.resolve(argv[rootFlag + 1]);
  const tokens = JSON.parse(fs.readFileSync(path.join(appDir, "design/design-tokens.json"), "utf8"));
  const compatibility = JSON.parse(fs.readFileSync(path.join(appDir, "design/public-theme-compatibility.json"), "utf8"));
  const output = renderTokens(tokens, compatibility);
  const destination = path.join(appDir, "app/public-tokens.css");
  if (!argv.includes("--check")) {
    fs.writeFileSync(destination, output);
    console.log("Generated app/public-tokens.css (inactive .gs-public-unified scope).");
    return;
  }
  const files = STYLE_FILES.map(filename => ({ filename, css: fs.readFileSync(path.join(appDir, "app", filename), "utf8").replace(/\r\n/g, "\n") }));
  const issues = [...inspectStyles(files), ...inspectContrastPolicy(tokens, compatibility)];
  if (files[0].css !== output) issues.unshift("Token CSS differs from its JSON sources; run node scripts/public-design-tokens.cjs.");
  if (issues.length) throw new Error(issues.join("\n"));
  for (const [role, entry] of Object.entries(CONTRAST_ALLOWLIST)) console.log(`ALLOW ${role}: ${entry.reason}`);
  console.log("PASS: four foundation stylesheets plus country stylesheet; scoped tokens, sizes, shadows, centralized motion and small dark surfaces.");
}

module.exports = { STYLE_FILES, renderTokens, inspectStyles, CONTRAST_ALLOWLIST, checkContrastUse, inspectContrastPolicy, main };
if (require.main === module) {
  try { main(); } catch (error) { console.error(error.message); process.exitCode = 1; }
}
